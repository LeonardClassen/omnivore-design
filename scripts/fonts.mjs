// Self-hosted fonts: copies the latin + latin-ext variable woff2 files from the
// @fontsource-variable dev dependencies into fonts/ and writes fonts/fonts.css
// with the family names tokens.css expects. The HMI panel is offline, so the
// design system ships its fonts instead of pointing at a CDN.
// Usage: npm run fonts
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const FAMILIES = [
  ["inter", "Inter"],
  ["montserrat", "Montserrat"],
  ["jetbrains-mono", "JetBrains Mono"],
];
const SUBSETS = ["latin-ext", "latin"]; // German incl. umlauts + ß lives in "latin"

mkdirSync(here("../fonts"), { recursive: true });
const css = [
  "/* Omnivore Design System - self-hosted fonts (the HMI panel is offline).",
  " * Variable woff2, latin + latin-ext, from Fontsource (SIL OFL 1.1; licences in fonts/LICENSE-*.txt).",
  " * Generated by `npm run fonts` - do not edit. Load this file before tokens.css. */",
  "",
];

for (const [pkg, family] of FAMILIES) {
  const dir = here(`../node_modules/@fontsource-variable/${pkg}/`);
  const src = readFileSync(dir + "wght.css", "utf8");
  for (const subset of SUBSETS) {
    const block = src.match(new RegExp(`/\\* ${pkg}-${subset}-wght-normal \\*/\\s*@font-face \\{([^}]*)\\}`));
    if (!block) throw new Error(`${pkg}: no ${subset} block in wght.css`);
    const body = block[1];
    const file = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
    const range = body.match(/unicode-range:\s*([^;]+);/)[1].trim();
    const weight = body.match(/font-weight:\s*([^;]+);/)[1].trim();
    copyFileSync(dir + "files/" + file, here("../fonts/" + file));
    css.push(
      "@font-face {",
      `  font-family: "${family}";`,
      "  font-style: normal;",
      "  font-display: swap;",
      `  font-weight: ${weight};`,
      `  src: url("./${file}") format("woff2-variations"), url("./${file}") format("woff2");`,
      `  unicode-range: ${range};`,
      "}",
      "",
    );
  }
  copyFileSync(dir + "LICENSE", here(`../fonts/LICENSE-${pkg}.txt`));
}

writeFileSync(here("../fonts/fonts.css"), css.join("\n"));
console.log(`fonts.css: ${FAMILIES.length} families x ${SUBSETS.length} subsets`);
